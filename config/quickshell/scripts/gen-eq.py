#!/usr/bin/env python3
"""Generate ~/.config/pipewire/pipewire.conf.d/eq32.conf for the rice equalizer.

Chain (per channel):  preamp -> high-pass -> low-pass -> 32 peaking bands -> limiter

The limiter is the LADSPA "Fast Lookahead Limiter" from swh-plugins when it is
installed (a real, transparent limiter). Without it the chain ends in a hard
clip at the ceiling, which protects just as well but distorts when it is hit.

    gen-eq.py              write the config
    gen-eq.py --restart    write it and restart PipeWire (falls back to the
                           hard clip if the filter doesn't come up)
    gen-eq.py --no-limiter force the hard-clip variant

Controls are set live by ~/.config/quickshell/services/Eq.qml.
"""
import os
import subprocess
import sys
import time

BANDS = 32
Q = 4.32
LIMITER_NAME = "fast_lookahead_limiter_1913.so"
# Where swh-plugins puts LADSPA plugins: Arch (/usr/lib), NixOS (system profile, user profile), or LADSPA_PATH.
LADSPA_DIRS = [d for d in os.environ.get("LADSPA_PATH", "").split(":") if d] + [
    "/usr/lib/ladspa", "/usr/local/lib/ladspa", "/run/current-system/sw/lib/ladspa",
    os.path.expanduser("~/.nix-profile/lib/ladspa"), "/etc/profiles/per-user/" + os.environ.get("USER", "") + "/lib/ladspa",
]
LIMITER_SO = next((os.path.join(d, LIMITER_NAME) for d in LADSPA_DIRS if os.path.exists(os.path.join(d, LIMITER_NAME))),
                  "/usr/lib/ladspa/" + LIMITER_NAME)
LIMITER_LABEL = "fastLookaheadLimiter"
CONF = os.path.expanduser("~/.config/pipewire/pipewire.conf.d/eq32.conf")
# Low-pass "off": at or above Nyquist the biquad is a straight pass-through.
LP_OFF = 1000000.0


def freqs():
    return [20.0 * 1000.0 ** (i / (BANDS - 1)) for i in range(BANDS)]


def graph(limiter):
    nodes, links = [], []
    ind = " " * 20

    def node(name, label, control):
        ctl = " ".join(f'"{k}" = {v}' for k, v in control.items())
        nodes.append(f"{ind}{{ type = builtin  name = {name}  label = {label}\n"
                     f"{ind}  control = {{ {ctl} }} }}")

    def link(a, b):
        links.append(f'{ind}{{ output = "{a}" input = "{b}" }}')

    for ch in ("L", "R"):
        node(f"preamp{ch}", "linear", {"Mult": 1.0, "Add": 0.0})
        node(f"hp{ch}", "bq_highpass", {"Freq": 0.0, "Q": 0.707})
        node(f"lp{ch}", "bq_lowpass", {"Freq": LP_OFF, "Q": 0.707})
        link(f"preamp{ch}:Out", f"hp{ch}:In")
        link(f"hp{ch}:Out", f"lp{ch}:In")
        prev = f"lp{ch}:Out"
        for i, f in enumerate(freqs(), 1):
            node(f"b{i}{ch}", "bq_peaking", {"Freq": round(f, 1), "Q": Q, "Gain": 0.0})
            link(prev, f"b{i}{ch}:In")
            prev = f"b{i}{ch}:Out"
        if not limiter:
            node(f"lim{ch}", "clamp", {"Min": -1.0, "Max": 1.0})
            link(prev, f"lim{ch}:In")

    if limiter:
        nodes.append(f"{ind}{{ type = ladspa  name = lim  plugin = \"{LIMITER_SO}\"  label = {LIMITER_LABEL}\n"
                     f"{ind}  control = {{ \"Input gain (dB)\" = 0.0 \"Limit (dB)\" = 0.0 \"Release time (s)\" = 0.2 }} }}")
        link(f"b{BANDS}L:Out", "lim:Input 1")
        link(f"b{BANDS}R:Out", "lim:Input 2")
        outputs = '"lim:Output 1" "lim:Output 2"'
    else:
        outputs = '"limL:Out" "limR:Out"'

    return (f"                nodes = [\n" + "\n".join(nodes) + "\n                ]\n"
            f"                links = [\n" + "\n".join(links) + "\n                ]\n"
            f'                inputs  = [ "preampL:In" "preampR:In" ]\n'
            f"                outputs = [ {outputs} ]\n")


def args(limiter, prefix="eq32", smart=True, target=None):
    capture = [f'node.name         = "{prefix}_input"', "media.class       = Audio/Sink"]
    playback = [f'node.name    = "{prefix}_output"']
    if smart:
        capture += ["filter.smart      = true", f'filter.smart.name = "{prefix}"']
        playback += ["node.passive = true"]
    if target:
        playback += [f'target.object = "{target}"']
    pad = "\n                "
    return ("{\n"
            '            node.description = "Equalizer"\n'
            '            media.name       = "Equalizer"\n'
            "            filter.graph = {\n" + graph(limiter) + "            }\n"
            "            audio.channels = 2\n"
            "            audio.position = [ FL FR ]\n"
            "            capture.props = {" + pad + pad.join(capture) + "\n            }\n"
            "            playback.props = {" + pad + pad.join(playback) + "\n            }\n"
            "        }")


def conf(limiter):
    kind = (f"limiter: LADSPA {LIMITER_LABEL} (swh-plugins)" if limiter
            else "limiter: hard clip (install swh-plugins and re-run gen-eq.py for a real one)")
    return ("# 32-band graphic equalizer (managed by the Quickshell rice).\n"
            "# GENERATED by ~/.config/quickshell/scripts/gen-eq.py - edit that instead.\n"
            f"# {kind}\n"
            "# Chain per channel: preamp -> high-pass -> low-pass -> 32 peaking bands\n"
            "# (log-spaced 20 Hz - 20 kHz, ~1/3 octave) -> limiter. Controls are set live\n"
            "# by ~/.config/quickshell/services/Eq.qml via `pw-cli set-param`.\n"
            '# It is a WirePlumber "smart filter": automatically placed in front of the\n'
            "# default output, so apps and volume keys keep using the real device.\n"
            "context.modules = [\n"
            "    { name = libpipewire-module-filter-chain\n"
            "        flags = [ nofail ]\n"
            "        args = " + args(limiter) + "\n"
            "    }\n"
            "]\n")


def write(limiter):
    os.makedirs(os.path.dirname(CONF), exist_ok=True)
    with open(CONF, "w") as f:
        f.write(conf(limiter))
    print(f"wrote {CONF} ({'lookahead limiter' if limiter else 'hard-clip ceiling'})")


def node_up(timeout=8.0):
    end = time.time() + timeout
    while time.time() < end:
        out = subprocess.run(["pw-cli", "ls", "Node"], capture_output=True, text=True).stdout
        if '"eq32_input"' in out:
            return True
        time.sleep(0.4)
    return False


def restart():
    units = ["pipewire", "wireplumber"]
    if subprocess.run(["systemctl", "--user", "is-active", "-q", "pipewire-pulse"]).returncode == 0:
        units.append("pipewire-pulse")
    subprocess.run(["systemctl", "--user", "restart", *units], check=False)


def main():
    argv = sys.argv[1:]
    if "-h" in argv or "--help" in argv:
        print(__doc__)
        return 0
    limiter = os.path.exists(LIMITER_SO) and "--no-limiter" not in argv
    if "--test-args" in argv:   # module args for a throwaway, non-smart instance
        target = argv[argv.index("--test-args") + 1]
        print(args(limiter, prefix="eqtest", smart=False, target=target))
        return 0
    write(limiter)
    if "--restart" in argv:
        restart()
        if not node_up() and limiter:
            print("filter did not start with the LADSPA limiter; falling back to the hard clip")
            write(False)
            restart()
        if not node_up():
            print("equalizer node did not come up - check `journalctl --user -u pipewire -n 50`")
            return 1
        print("equalizer is running")
    return 0


if __name__ == "__main__":
    sys.exit(main())
